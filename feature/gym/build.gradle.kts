// Builds program/PROGRAM.md into the app as a string, so the gym works with no server at all. The
// server's copy replaces it once the app has synced.
val generateBundledProgram by tasks.registering {
    val input = rootProject.layout.projectDirectory.file("program/PROGRAM.md")
    val output = layout.buildDirectory.dir("generated/program/commonMain/kotlin")
    inputs.file(input)
    outputs.dir(output)
    doLast {
        val escaped = buildString {
            input.asFile.readText().forEach { char ->
                when (char) {
                    '\\' -> append("\\\\")
                    '"' -> append("\\\"")
                    '$' -> append("\\$")
                    '\n' -> append("\\n")
                    '\r' -> Unit
                    else -> append(char)
                }
            }
        }
        val file = output.get().file("dev/habita/app/feature/gym/data/BundledProgram.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            "package dev.habita.app.feature.gym.data\n\n" +
                "/** program/PROGRAM.md at build time. Generated by the build; do not edit. */\n" +
                "internal const val BUNDLED_PROGRAM: String = \"$escaped\"",
        )
    }
}

kotlin {
    jvm("desktop") {
        compilerOptions {
            jvmTarget.set(JvmTarget.JVM_17)
        }
    }

    android {
        namespace = libs.versions.feature.gym.group.get()
        compileSdk = libs.versions.android.compileSdk.get().toInt()
        minSdk = libs.versions.android.minSdk.get().toInt()
    }

    sourceSets {
        commonMain {
            kotlin.srcDir(generateBundledProgram)
        }

        commonMain.dependencies {
