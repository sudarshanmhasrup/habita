package dev.habita.app.core.theme

import androidx.compose.ui.unit.dp

/**
 * The spacing scale, on a 4 dp grid. Screens use [screen] at the sides, [section] between groups,
 * [item] between cards in a group, and [inside] as the gap between a label and what it labels.
 */
object Space {
    val tiny = 4.dp
    val inside = 8.dp
    val item = 12.dp
    val card = 20.dp
    val section = 28.dp
    val screen = 24.dp
}