    alias(libs.plugins.compose.multiplatform)
}

group = libs.versions.desktop.group.get()
version = libs.versions.desktop.version.get()

// The desktop app reads the same settings as android/ and ios/: local.properties, a Gradle
// property or an environment variable, in that order. They are built in as constants.
val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use(::load)
}

fun rawSetting(name: String): String {
    val value = localProperties.getProperty(name)
        ?: providers.gradleProperty(name).orNull
        ?: providers.environmentVariable(name).orNull
        ?: ""
    return value.trim()
}

fun kotlinString(value: String): String =
    "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""

val generateDesktopConfig by tasks.registering {
    val contents = "package dev.habita.app.desktop\n\n" +
        "import dev.habita.app.core.AppConfig\n\n" +
        "/** App settings from local.properties at build time. Generated by the build; do not edit. */\n" +
        "internal val DESKTOP_CONFIG: AppConfig = AppConfig(\n" +
        "    serverUrl = ${kotlinString(rawSetting("HABITA_SERVER_URL"))},\n" +
        "    userName = ${kotlinString(rawSetting("HABITA_NAME"))},\n" +
        "    loginEnabled = ${rawSetting("HABITA_LOGIN") == "true"},\n" +
        ")"
    val output = layout.buildDirectory.dir("generated/config/kotlin")
    inputs.property("contents", contents)
    outputs.dir(output)
    doLast {
        val file = output.get().file("dev/habita/app/desktop/DesktopConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(contents)
    }
}

kotlin {
    jvmToolchain(21)
    sourceSets.main {
        kotlin.srcDir(generateDesktopConfig)
    }
}

