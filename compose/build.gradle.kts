import java.util.Properties
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    alias(libs.plugins.kotlin.multiplatform)
    alias(libs.plugins.android.kotlin.multiplatform.library)
    alias(libs.plugins.compose.compiler)
    // Copies the Compose resources of every module into the iOS app.
    alias(libs.plugins.compose.multiplatform)
}

group = libs.versions.compose.group.get()
version = libs.versions.compose.version.get()

// The iOS app reads the same settings as android/: local.properties, a Gradle property or an
// environment variable, in that order. They are built into the framework as constants.
val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use(::load)
}

fun rawSetting(name: String): String {
    val value = localProperties.getProperty(name)
        ?: providers.gradleProperty(name).orNull
        ?: providers.environmentVariable(name).orNull
        ?: ""
    return value.trim()
}

fun kotlinString(value: String): String =
    "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""

val generateIosConfig by tasks.registering {
    val contents = "package dev.habita.app.compose\n\n" +
        "import dev.habita.app.core.AppConfig\n\n" +
        "/** App settings from local.properties at build time. Generated by the build; do not edit. */\n" +
        "internal val IOS_CONFIG: AppConfig = AppConfig(\n" +
        "    serverUrl = ${kotlinString(rawSetting("HABITA_SERVER_URL"))},\n" +
        "    userName = ${kotlinString(rawSetting("HABITA_NAME"))},\n" +
        "    loginEnabled = ${rawSetting("HABITA_LOGIN") == "true"},\n" +
        ")"
    val output = layout.buildDirectory.dir("generated/config/iosMain/kotlin")
    inputs.property("contents", contents)
    outputs.dir(output)
    doLast {
        val file = output.get().file("dev/habita/app/compose/IosConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(contents)
    }
}

